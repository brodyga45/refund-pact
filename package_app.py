#!/usr/bin/env python3
"""Prepare a local UNA package; this does not publish or enter a competition."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import struct
import subprocess
import sys
import tempfile
import zipfile
import zlib

DEVELOPMENT_ID = "BEC65A5C096E4894"
ROOT = Path(__file__).resolve().parent


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--app-id", required=True, help="ID generated by the UNA app portal")
    parser.add_argument("--development", action="store_true", help="Allow the development-only ID")
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()
    app_id = args.app_id.upper()
    if not re.fullmatch(r"[0-9A-F]{16}", app_id):
        parser.error("App ID must have exactly 16 hexadecimal digits")
    if app_id == DEVELOPMENT_ID and not args.development:
        parser.error("Development ID requires --development; obtain a portal ID for publication")
    sdk = Path(os.environ.get("UNA_SDK", ""))
    resolver = sdk / "Utilities/Scripts/app_packer/min_kernel_version.py"
    if not resolver.is_file():
        parser.error("Set UNA_SDK to the pinned SDK checkout")
    binary = ROOT / "Output/RallySlate_0.1.0.uapp"
    data = binary.read_bytes()
    if len(data) < 52 or struct.unpack_from("<Q", data)[0] != int(app_id, 16):
        parser.error("Binary ID differs from requested ID: reconfigure and rebuild firmware")
    if zlib.crc32(data[:-4]) & 0xFFFFFFFF != struct.unpack_from("<I", data, len(data)-4)[0]:
        parser.error("Binary CRC check failed")
    if struct.unpack_from("<I", data, 8)[0] != 0x00000100:
        parser.error("Binary version differs from package version 0.1.0")
    if b"/Users/" in data:
        parser.error("Binary contains a local user path; inspect the build before packaging")
    manifest = {
        "manifest_version": 1, "type": ["utility"], "name": "Rally Slate",
        "description": "Offline two-sided rally scoring with full-round undo and visible save recovery.",
        "icon": "icon.png", "binary": binary.name, "appVersion": "0.1.0",
        "requiredHardware": [], "stravaExport": False, "id": app_id,
        "supportsLaps": False, "supportsDistance": False, "supportsTrack": False,
        "supportsHeartbeat": False, "supportsElevation": False, "supportsStep": False,
        "supportsSpeed": "none", "customMeasures": []
    }
    with tempfile.TemporaryDirectory(prefix="rally-package-") as folder:
        path = Path(folder) / "app-manifest.json"
        path.write_text(json.dumps(manifest, indent=2) + "\n")
        subprocess.run([sys.executable, str(resolver), "--stamp", str(path)], check=True)
        subprocess.run([sys.executable, str(resolver), "--check", str(path)], check=True)
        args.output.parent.mkdir(parents=True, exist_ok=True)
        with zipfile.ZipFile(args.output, "x", compression=zipfile.ZIP_DEFLATED) as archive:
            archive.writestr(binary.name, data)
            archive.write(path, "app-manifest.json")
            archive.write(ROOT / "Resources/icon_60x60.png", "icon.png")
            for name in ["LICENSE", "THIRD-PARTY-NOTICES.md"]:
                archive.write(ROOT / name, name)
            for notice in sorted((ROOT / "licenses").glob("*.txt")):
                archive.write(notice, "licenses/" + notice.name)
            if args.development:
                archive.writestr("DEVELOPMENT-ONLY.txt", "Local development preview. No portal ID, publication, contest entry, award or payment is established.\n")
    print(json.dumps({"archive": str(args.output), "sha256": hashlib.sha256(args.output.read_bytes()).hexdigest(),
                      "app_id": app_id, "development": args.development,
                      "published": False, "submitted": False}))


if __name__ == "__main__":
    main()
